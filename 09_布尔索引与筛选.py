# ============================================================
# 第9章：布尔索引与筛选 —— 按条件选数据
# ============================================================
# 这是数据分析中最常用的操作之一。
# 想象你有一张成绩表，你想找出"所有及格的人"、"数学超过 90 分的"、
# "分数在 80 到 90 之间的"等等。
#
# 布尔索引就是：用一个 True/False 数组来筛选原数组，只保留 True 位置的元素。

import numpy as np


# ============================================================
# 9.1 基础：用比较运算产生布尔数组
# ============================================================
# 比较运算（>, <, ==, != 等）作用在数组上，会返回一个布尔数组。

print("=" * 50)
print("9.1 产生布尔数组")

scores = np.array([85, 92, 45, 78, 60, 95, 33, 88])
print(f"成绩: {scores}")

# 每个成绩 >= 60 吗？
passed = scores >= 60
print(f"是否及格: {passed}")
# [True, True, False, True, True, True, False, True]

# 每个成绩 == 95 吗？
is_95 = scores == 95
print(f"是否等于95: {is_95}")


# ============================================================
# 9.2 用布尔数组做筛选 —— 这才是重点！
# ============================================================
# 把布尔数组放在方括号里，就能筛选出 True 位置的元素。

print("\n" + "=" * 50)
print("9.2 布尔索引筛选")

scores = np.array([85, 92, 45, 78, 60, 95, 33, 88])

# 筛选出及格的成绩
passed_scores = scores[scores >= 60]
print(f"及格的成绩: {passed_scores}")
# 只有 True 位置的元素被保留

# 筛选出优秀成绩（>= 90）
excellent = scores[scores >= 90]
print(f"优秀成绩: {excellent}")

# 筛选出不及格的成绩（< 60）
failed = scores[scores < 60]
print(f"不及格的成绩: {failed}")


# ============================================================
# 9.3 组合多个条件 —— &, |, ~
# ============================================================
# 想同时满足多个条件？用 &（与）、|（或）、~（非）。
# 注意：每个条件必须用括号括起来！这是新手最容易出错的地方。

print("\n" + "=" * 50)
print("9.3 组合多个条件")

scores = np.array([85, 92, 45, 78, 60, 95, 33, 88])

# 找出 70 到 90 之间的成绩（包含 70，不包含 90）
# 注意：必须用 &，不能用 and；每个条件要加括号！
mid_range = scores[(scores >= 70) & (scores < 90)]
print(f"70~90 之间的成绩: {mid_range}")

# 找出不及格（< 60）或满分（>= 95）的
# 注意：必须用 |，不能用 or
extreme = scores[(scores < 60) | (scores >= 95)]
print(f"不及格或满分: {extreme}")

# 找出不是在 80~90 之间的（用 ~ 取反）
not_80_90 = scores[~((scores >= 80) & (scores <= 90))]
print(f"不在 80~90 之间的: {not_80_90}")

# 常见错误示范（不要这样写！）：
# scores[scores >= 70 and scores < 90]  ← 错误！会报错
# 为什么？因为 Python 的 and/or 不能用于数组，必须用 & 和 |


# ============================================================
# 9.4 二维数组的布尔索引
# ============================================================
print("\n" + "=" * 50)
print("9.4 二维数组的布尔索引")

grades = np.array([[85, 92, 78],
                   [60, 45, 88],
                   [95, 89, 55],
                   [73, 81, 68]])
print("成绩表 (4个学生, 3科):")
print(grades)

# 找出所有及格的成绩（返回一维数组）
passed = grades[grades >= 60]
print(f"\n所有及格的成绩: {passed}")

# 找出所有不及格的位置
failure_mask = grades < 60
print(f"\n不及格的位置 (True=不及格):\n{failure_mask}")

# 把不及格的成绩替换成 60
grades_corrected = grades.copy()
grades_corrected[grades_corrected < 60] = 60
print(f"\n把不及格改为60:\n{grades_corrected}")
# 这是非常实用的技巧：用布尔索引直接修改数据！


# ============================================================
# 9.5 np.where —— 更灵活的条件筛选
# ============================================================
# np.where 是布尔索引的升级版，可以做到"如果条件成立选 A，否则选 B"

print("\n" + "=" * 50)
print("9.5 np.where —— 条件选择")

scores = np.array([85, 92, 45, 78, 60, 95, 33, 88])

# np.where(条件, 成立时的值, 不成立时的值)
result = np.where(scores >= 60, "及格", "不及格")
print(f"成绩: {scores}")
print(f"判定: {result}")

# 把不及格的变成 60，其他的不变
adjusted = np.where(scores < 60, 60, scores)
print(f"把不及格改为60: {adjusted}")

# np.where 也可以用来找位置
# np.where(条件) 返回满足条件的索引
low_indices = np.where(scores < 60)
print(f"不及格的索引: {low_indices[0]}")
print(f"不及格的成绩: {scores[low_indices]}")


# ============================================================
# 9.6 实战：筛选学生数据
# ============================================================
print("\n" + "=" * 50)
print("9.6 实战：学生成绩筛选")

# 模拟一个学生成绩表：4 个学生，3 科成绩
grades = np.array([[85, 92, 78],   # 学生 0
                   [60, 45, 88],   # 学生 1
                   [95, 89, 55],   # 学生 2
                   [73, 81, 68]])  # 学生 3

print("成绩表:")
print(grades)

# 找出"每科都及格"的学生（所有科目 >= 60）
all_pass = (grades >= 60).all(axis=1)  # 每行是否全 True
print(f"\n所有科目都及格的学生: {np.where(all_pass)[0]}")

# 找出"至少有一科不及格"的学生
any_fail = (grades < 60).any(axis=1)
print(f"至少有一科不及格的学生: {np.where(any_fail)[0]}")

# 统计每个学生不及格科目数
fail_count = (grades < 60).sum(axis=1)
print(f"每个学生不及格科目数: {fail_count}")


# ============================================================
# 本章总结
# ============================================================
print("\n" + "=" * 50)
print("【本章总结】")
print("""
  arr[arr > 60]              → 筛选出大于 60 的元素
  arr[(arr > 60) & (arr < 90)] → 组合条件（必须用 & |  ~）
  arr[arr < 60] = 60         → 把不及格的全部改成 60
  np.where(条件, A, B)        → 条件成立选 A，否则选 B
  np.where(条件)              → 返回满足条件的索引

三个关键点：
  1. 组合条件用 & | ~，不要用 and or not
  2. 每个条件必须加括号，如 (arr > 60) & (arr < 90)
  3. 布尔索引可以直接用来修改数组！如 arr[arr < 0] = 0
""")