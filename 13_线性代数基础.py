# 本章总结
# ============================================================
print("\n" + "=" * 50)
print("【本章总结】")
print("""
线性代数核心函数：
  A @ B                    → 矩阵乘法
  np.linalg.inv(A)         → 矩阵的逆
  np.linalg.det(A)         → 行列式（=0 意味着不可逆）
  np.linalg.solve(A, b)    → 解线性方程组 Ax = b
  np.linalg.eig(A)         → 特征值和特征向量
  np.linalg.norm(v)        → 向量的范数（大小）

关键点：
  1. * 是逐元素乘法，@ 才是矩阵乘法
  2. 不是所有矩阵都可逆（行列式为 0 的不可逆）
  3. solve 比 inv 更高效：解方程直接用 solve，别先求逆再乘
  4. 浮点运算有精度误差，用 np.allclose() 而不是 == 来比较
""")