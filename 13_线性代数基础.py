# ============================================================
# 第13章：线性代数基础 —— 矩阵运算的科学计算
# ============================================================
# 线性代数是 NumPy 的"根"——NumPy 本来就是为科学计算而生的。
# 矩阵乘法、求逆、解方程组……这些操作在机器学习、图像处理、
# 物理模拟中无处不在。
#
# 本章介绍 np.linalg 模块中最常用的函数。你不需要是数学专家，
# 理解这些函数"做什么"就够了。

import numpy as np


# ============================================================
# 13.1 矩阵乘法回顾 —— @ 和 np.dot
# ============================================================
# 在 NumPy 中，* 是逐元素乘法，@ 是矩阵乘法（点积）。
# 这很重要！用错了符号，结果完全不一样。

print("=" * 50)
print("13.1 矩阵乘法：@ vs *")

A = np.array([[1, 2],
              [3, 4]])
B = np.array([[5, 6],
              [7, 8]])

# 逐元素乘法：对应位置相乘
print(f"逐元素乘法 A * B:\n{A * B}")
# [[1*5, 2*6],
#  [3*7, 4*8]]

# 矩阵乘法（点积）：行×列
print(f"\n矩阵乘法 A @ B:\n{A @ B}")
# [[1*5+2*7, 1*6+2*8],
#  [3*5+4*7, 3*6+4*8]]

# np.dot 和 @ 等价
print(f"\nnp.dot(A, B) 和 A @ B 一样:\n{np.dot(A, B)}")


# ============================================================
# 13.2 矩阵的逆 —— np.linalg.inv
# ============================================================
# 逆矩阵 A⁻¹ 满足：A @ A⁻¹ = I（单位矩阵）
# 不是所有矩阵都有逆矩阵（奇异矩阵就没有），如果矩阵不可逆，会报错。
#
# 类比：乘以逆矩阵就像"除以"这个矩阵。解方程时的关键工具。

print("\n" + "=" * 50)
print("13.2 矩阵的逆")

A = np.array([[1, 2],
              [3, 4]])
print(f"矩阵 A:\n{A}")

A_inv = np.linalg.inv(A)
print(f"\nA 的逆矩阵:\n{A_inv}")

# 验证：A @ A_inv = I（单位矩阵）
print(f"\n验证 A @ A_inv = I:\n{A @ A_inv}")
# 对角线是 1，其他位置接近 0（可能有浮点精度误差）

# 什么样的矩阵没有逆矩阵？
# 如果矩阵的行列式为 0（或接近 0），就没有逆矩阵
singular = np.array([[1, 2],
                     [2, 4]])  # 第二行是第一行的 2 倍
print(f"\n奇异矩阵:\n{singular}")
try:
    np.linalg.inv(singular)
except np.linalg.LinAlgError as e:
    print(f"果然报错了: {e}")
    print("因为第二行是第一行的 2 倍，行列式为 0")


# ============================================================
# 13.3 行列式 —— np.linalg.det
# ============================================================
# 行列式是一个标量，反映了矩阵的"缩放因子"。
# 行列式为 0 意味着矩阵把空间"压扁"了（不可逆）。
# 行列式 > 0 意味着保持方向，< 0 意味着翻转了方向。

print("\n" + "=" * 50)
print("13.3 行列式")

A = np.array([[1, 2],
              [3, 4]])
print(f"矩阵 A 的行列式: {np.linalg.det(A):.2f}")
# 2×2 矩阵行列式 = a*d - b*c = 1*4 - 2*3 = -2

# 奇异矩阵的行列式为 0
print(f"奇异矩阵的行列式: {np.linalg.det(singular):.2f}")
# 1*4 - 2*2 = 0

# 三维矩阵的行列式
B = np.array([[1, 0, 0],
              [0, 2, 0],
              [0, 0, 3]])
print(f"对角矩阵 B 的行列式: {np.linalg.det(B):.2f}")
# 对角矩阵的行列式 = 对角线元素乘积 = 1*2*3 = 6


# ============================================================
# 13.4 解线性方程组 —— np.linalg.solve
# ============================================================
# 这是线性代数最重要的应用之一。
# 方程组：  Ax = b  →  求解 x
# 例如：  x + 2y = 5
#         3x + 4y = 6
# 求 x 和 y 的值。

print("\n" + "=" * 50)
print("13.4 解线性方程组")

# 方程组：
#   x + 2y = 5
#   3x + 4y = 6
A = np.array([[1, 2],
              [3, 4]])
b = np.array([5, 6])

print("方程组:")
print("  x + 2y = 5")
print("  3x + 4y = 6")

x = np.linalg.solve(A, b)
print(f"\n求解结果: x = {x[0]:.1f}, y = {x[1]:.1f}")

# 验证：把解代回去
print(f"验证: x + 2y = {x[0] + 2*x[1]:.1f}  (应为 5)")
print(f"验证: 3x + 4y = {3*x[0] + 4*x[1]:.1f}  (应为 6)")

# 更大的方程组
A2 = np.array([[1, 2, 3],
               [2, 5, 2],
               [3, 1, 5]])
b2 = np.array([14, 18, 20])
x2 = np.linalg.solve(A2, b2)
print(f"\n3元方程组解: {x2}")
print(f"验证 Ax ≈ b: {A2 @ x2}")


# ============================================================
# 13.5 特征值与特征向量 —— np.linalg.eig
# ============================================================
# 特征值和特征向量是矩阵的"指纹"。
# 它们满足：A @ v = λ * v（矩阵乘以向量 = 标量乘以向量）
# 广泛应用于：PCA降维、PageRank算法、振动分析等。

print("\n" + "=" * 50)
print("13.5 特征值与特征向量")

A = np.array([[1, 2],
              [2, 1]])

eigenvalues, eigenvectors = np.linalg.eig(A)

print(f"矩阵 A:\n{A}")
print(f"\n特征值: {eigenvalues}")
print(f"特征向量（每列是一个特征向量）:\n{eigenvectors}")

# 验证：A @ v = λ * v
for i in range(2):
    v = eigenvectors[:, i]
    lam = eigenvalues[i]
    Av = A @ v
    lam_v = lam * v
    print(f"\n验证特征值 {lam:.1f}:")
    print(f"  A @ v = {Av}")
    print(f"  λ * v = {lam_v}")
    print(f"  是否相等: {np.allclose(Av, lam_v)}")


# ============================================================
# 13.6 范数 —— np.linalg.norm
# ============================================================
# 范数衡量向量/矩阵的"大小"。
# 最常见的：L2 范数（欧几里得距离），即 √(x₁² + x₂² + ... + xₙ²)

print("\n" + "=" * 50)
print("13.6 范数（向量/矩阵的大小）")

v = np.array([3, 4])
print(f"向量 v = {v}")
print(f"L2 范数（勾股定理）: {np.linalg.norm(v)}")
print(f"  验证: √(3² + 4²) = √25 = 5 ✓")

# 矩阵的范数
A = np.array([[1, 2],
              [3, 4]])
print(f"\n矩阵 A 的 Frobenius 范数: {np.linalg.norm(A):.2f}")
print(f"  验证: √(1²+2²+3²+4²) = √30 ≈ 5.48 ✓")


