# ============================================================
# 第5章：形状操作 —— 改变数组的"外观"
# ============================================================
# 有时候你需要改变数组的形状，比如把一行数据变成矩阵，
# 或者把多维数组展平成一维。但注意：改变形状不会改变数据本身，
# 只是换了一种"看"数据的方式。
#
# 类比：同一块橡皮泥，你可以捏成球，也可以压成饼——
# 本质还是那块橡皮泥，只是形状变了。

import numpy as np


# ============================================================
# 5.1 reshape —— 改变形状（最常用）
# ============================================================
# reshape 让你把数组变成任意形状，只要元素总数不变。
# 比如有 12 个元素，可以变成 (3,4)、(4,3)、(2,6) 等等。

print("=" * 50)
print("5.1 reshape —— 改变形状")

# 一个一维数组，有 12 个元素
arr = np.arange(12)  # [0, 1, 2, ..., 11]
print(f"原数组 (一维): {arr}")
print(f"shape: {arr.shape}")

# 变成 3 行 4 列的矩阵
matrix_3x4 = arr.reshape(3, 4)
print(f"\n变成 3x4 矩阵:\n{matrix_3x4}")
print(f"shape: {matrix_3x4.shape}")

# 变成 4 行 3 列
matrix_4x3 = arr.reshape(4, 3)
print(f"\n变成 4x3 矩阵:\n{matrix_4x3}")

# 变成 2 行 6 列
matrix_2x6 = arr.reshape(2, 6)
print(f"\n变成 2x6 矩阵:\n{matrix_2x6}")

# 关键规则：reshape 前后元素总数必须相同！
# 12 个元素 = 3×4 = 4×3 = 2×6
# 如果你写 reshape(3, 5)，15 个元素 ≠ 12，就会报错。


# ============================================================
# 5.2 reshape 的自动推断：用 -1
# ============================================================
# 有时候你只知道想要几行，让 NumPy 自己算列数。
# 或者只知道想要几列，让 NumPy 自己算行数。
# 用 -1 表示"你帮我算"。

print("\n" + "=" * 50)
print("5.2 reshape 的自动推断（-1）")

arr = np.arange(12)

# 我想要 3 行，列数你帮我算
print(f"reshape(3, -1) → 3 行，自动算列数:\n{arr.reshape(3, -1)}")
# 12 ÷ 3 = 4 列，所以结果是 (3, 4)

# 我想要 4 列，行数你帮我算
print(f"\nreshape(-1, 4) → 自动算行数，4 列:\n{arr.reshape(-1, 4)}")
# 12 ÷ 4 = 3 行，所以结果是 (3, 4)

# 变成一维（不管原来几维，拍平）
arr_2d = np.array([[1, 2, 3], [4, 5, 6]])
print(f"\n原数组 (2x3):\n{arr_2d}")
print(f"reshape(-1) 拍平: {arr_2d.reshape(-1)}")
# 变成 [1, 2, 3, 4, 5, 6]


# ============================================================
# 5.3 flatten 和 ravel —— 把多维数组"拍平"成一维
# ============================================================
# 这两种方法都能把多维数组变成一维，但有一个关键区别。

print("\n" + "=" * 50)
print("5.3 flatten 和 ravel —— 拍平成一维")

arr = np.array([[1, 2, 3],
                [4, 5, 6]])
print(f"原数组:\n{arr}")

# flatten：返回一个副本（修改不影响原数组）
flat = arr.flatten()
print(f"flatten: {flat}")

# ravel：返回一个视图（如果可能的话，修改会影响原数组）
raveled = arr.ravel()
print(f"ravel: {raveled}")

# 验证区别
flat[0] = 999
print(f"\n修改 flatten 后，原数组不变:\n{arr}")

raveled[0] = 888
print(f"修改 ravel 后，原数组变了:\n{arr}")
# ravel 返回的是视图，所以修改会反映到原数组。

# 什么时候用哪个？
# - 需要独立副本，用 flatten()
# - 只想临时拍平，追求速度，用 ravel()


# ============================================================
# 5.4 转置 —— 行列互换
# ============================================================
# 把矩阵的行变成列，列变成行。在线性代数中非常常用。

print("\n" + "=" * 50)
print("5.4 转置（行列互换）")

arr = np.array([[1, 2, 3],
                [4, 5, 6]])
print(f"原数组 (2x3):\n{arr}")

# .T 属性：最简洁的转置方式
print(f"\n转置后 (3x2):\n{arr.T}")

# 也可以用 np.transpose(arr)，效果一样
print(f"\nnp.transpose:\n{np.transpose(arr)}")


# ============================================================
# 5.5 newaxis —— 增加一个维度
# ============================================================
# 有时候你需要把一维数组变成二维的"列向量"或"行向量"。
# 这在做矩阵运算时很常见。

print("\n" + "=" * 50)
print("5.5 newaxis —— 增加维度")

arr = np.array([1, 2, 3])
print(f"原数组: {arr}, shape: {arr.shape}")  # (3,)

# 变成列向量 (3行1列)
col = arr[:, np.newaxis]
print(f"\n列向量 (3x1):\n{col}")
print(f"shape: {col.shape}")

# 变成行向量 (1行3列)
row = arr[np.newaxis, :]
print(f"\n行向量 (1x3):\n{row}")
print(f"shape: {row.shape}")

# 实际场景：做矩阵乘法时，需要维度匹配
# 比如一个 (3,) 的向量没法直接和 (3,3) 的矩阵相乘，
# 需要先变成 (3,1) 的列向量


# ============================================================
# 本章总结
# ============================================================
print("\n" + "=" * 50)
print("【本章总结】")
print("""
  arr.reshape(行, 列)  → 改变形状（元素总数不能变）
  arr.reshape(-1)      → 拍平成一维
  arr.reshape(3, -1)   → 指定 3 行，列数自动算
  arr.flatten()        → 拍平（返回副本，安全）
  arr.ravel()          → 拍平（返回视图，快但注意副作用）
  arr.T                → 转置（行列互换）
  arr[:, np.newaxis]   → 升级为列向量
  arr[np.newaxis, :]   → 升级为行向量
""")